"""Write game/sprites.js from assets/sprites/*.json and assets/items/*.png, so the game can load
sprite data without a web server (opening game/index.html straight from disk can't fetch JSON).
usage: python tools/make_manifest.py"""
import glob, json, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}
for path in sorted(glob.glob(os.path.join(root, "assets", "sprites", "*.json"))):
    name = os.path.basename(path)[:-5]
    d = json.load(open(path))
    out[name] = {
        "src": f"../assets/sprites/{name}.png",
        "frames": d["frames"], "w": d["frame_w"], "h": d["frame_h"],
        "ms": d["ms_per_frame"], "loop": d["loop"], "pingpong": d.get("pingpong", False),
        "ax": d["anchor_x"], "ay": d["anchor_y"], "align": d.get("align", "feet"),
    }
items = sorted(os.path.basename(p)[:-4] for p in glob.glob(os.path.join(root, "assets", "items", "*.png")))
with open(os.path.join(root, "game", "sprites.js"), "w") as f:
    f.write("// Generated by tools/make_manifest.py. Don't edit by hand.\n")
    f.write("window.SPRITE_DATA = " + json.dumps(out, indent=1) + ";\n")
    f.write("window.ITEM_LIST = " + json.dumps(items) + ";\n")
print(f"{len(out)} sprites, {len(items)} items -> game/sprites.js")
